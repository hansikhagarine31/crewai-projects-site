// @vitest-environment jsdom
import { render, screen } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { describe, expect, it } from 'vitest';
import App from '../App.jsx';

describe('the footer note', () => {
  for (const path of ['/', '/projects/blog-post-crew', '/projects/unknown-project']) {
    it(`appears on ${path}`, () => {
      render(
        <MemoryRouter initialEntries={[path]}>
          <App />
        </MemoryRouter>,
      );
      const footer = screen.getAllByRole('contentinfo').at(-1);
      expect(footer).toHaveTextContent('The outputs on this site are generated by artificial intelligence and may contain errors.');
    });
  }
});
